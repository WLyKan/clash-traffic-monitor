CREATE TABLE IF NOT EXISTS hours (
 day TEXT NOT NULL, hour INTEGER NOT NULL CHECK(hour BETWEEN 0 AND 23),
 samples INTEGER NOT NULL DEFAULT 0, gap_seconds REAL NOT NULL DEFAULT 0,
 unattributed_up INTEGER NOT NULL DEFAULT 0, unattributed_down INTEGER NOT NULL DEFAULT 0,
 unmatched_up INTEGER NOT NULL DEFAULT 0, unmatched_down INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(day,hour)
);
CREATE TABLE IF NOT EXISTS apps (
 day TEXT NOT NULL, hour INTEGER NOT NULL CHECK(hour BETWEEN 0 AND 23),
 app TEXT NOT NULL COLLATE NOCASE, uploaded INTEGER NOT NULL, downloaded INTEGER NOT NULL,
 PRIMARY KEY(day,hour,app)
);
CREATE TABLE IF NOT EXISTS minutes (
 bucket INTEGER PRIMARY KEY, samples INTEGER NOT NULL DEFAULT 0,
 covered_seconds REAL NOT NULL DEFAULT 0, gap_seconds REAL NOT NULL DEFAULT 0,
 unattributed_up INTEGER NOT NULL DEFAULT 0, unattributed_down INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS minute_apps (
 bucket INTEGER NOT NULL REFERENCES minutes(bucket) ON DELETE CASCADE,
 app TEXT NOT NULL COLLATE NOCASE, uploaded INTEGER NOT NULL, downloaded INTEGER NOT NULL,
 PRIMARY KEY(bucket,app)
);
CREATE TABLE IF NOT EXISTS minute_residuals (
 bucket INTEGER NOT NULL REFERENCES minutes(bucket) ON DELETE CASCADE,
 segment REAL NOT NULL, up INTEGER NOT NULL, down INTEGER NOT NULL,
 PRIMARY KEY(bucket,segment)
);
CREATE TABLE IF NOT EXISTS targets (
 day TEXT NOT NULL, hour INTEGER NOT NULL, app TEXT NOT NULL COLLATE NOCASE,
 target TEXT NOT NULL, uploaded INTEGER NOT NULL, downloaded INTEGER NOT NULL,
 PRIMARY KEY(day,hour,app,target)
);
CREATE TABLE IF NOT EXISTS minute_targets (
 bucket INTEGER NOT NULL REFERENCES minutes(bucket) ON DELETE CASCADE,
 app TEXT NOT NULL COLLATE NOCASE, target TEXT NOT NULL,
 uploaded INTEGER NOT NULL, downloaded INTEGER NOT NULL,
 PRIMARY KEY(bucket,app,target)
);
CREATE TABLE IF NOT EXISTS spike_settings (
 id INTEGER PRIMARY KEY CHECK(id=1), enabled INTEGER NOT NULL CHECK(enabled IN (0,1)),
 threshold_mib INTEGER NOT NULL CHECK(threshold_mib>0)
);
CREATE TABLE IF NOT EXISTS checkpoint (
 id INTEGER PRIMARY KEY CHECK(id=1), sampled_at REAL NOT NULL
);
